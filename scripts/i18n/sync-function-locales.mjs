#!/usr/bin/env node
import { existsSync, readFileSync, writeFileSync } from "node:fs"
import path from "node:path"
import process from "node:process"
import { fileURLToPath } from "node:url"

const repoRoot = path.resolve(fileURLToPath(new URL("../..", import.meta.url)))
const args = new Set(process.argv.slice(2))
const sourcePath = path.join(repoRoot, "src/i18n/locales.source.json")
const generatedPath = path.join(repoRoot, "functions/localeSource.generated.mjs")

function renderFunctionLocaleSource(localeSource) {
    return `// Generated from src/i18n/locales.source.json by scripts/i18n/sync-function-locales.mjs.
// Do not edit this file directly.

const localeSource = ${JSON.stringify(localeSource, null, 4)}

export default localeSource
`
}

function fail(message) {
    throw new Error(message)
}

try {
    const localeSource = JSON.parse(readFileSync(sourcePath, "utf8"))
    const expected = renderFunctionLocaleSource(localeSource)

    if (args.has("--write")) {
        writeFileSync(generatedPath, expected)
        console.log("Updated functions/localeSource.generated.mjs")
        process.exit(0)
    }

    if (!existsSync(generatedPath)) {
        fail("functions/localeSource.generated.mjs is missing. Run pnpm i18n:sync-function-locales:write.")
    }

    const current = readFileSync(generatedPath, "utf8")
    if (current !== expected) {
        fail("functions/localeSource.generated.mjs drifted. Run pnpm i18n:sync-function-locales:write.")
    }

    console.log("function locale source is in sync")
} catch (error) {
    console.error(error instanceof Error ? error.message : error)
    process.exit(1)
}
